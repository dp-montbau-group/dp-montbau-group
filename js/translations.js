document.addEventListener("DOMContentLoaded", () => {

    const languageButtons =
        document.querySelectorAll("[data-lang]");

    const translatableElements =
        document.querySelectorAll("[data-i18n]");


    function applyTranslation(element, translation) {

        const hasMarkup =
            /<br\s*\/?>|<span\b/i.test(translation);


        if (hasMarkup) {

            element.innerHTML = translation;

            return;
        }


        const textNodes =
            Array.from(element.childNodes).filter(
                node =>
                    node.nodeType === Node.TEXT_NODE &&
                    node.textContent.trim()
            );


        if (textNodes.length > 0) {

            textNodes[0].textContent =
                "\n                " +
                translation +
                "\n                ";

        } else {

            element.textContent = translation;

        }

    }


    function setLanguage(language) {

        const dictionary =
            translations[language];

        if (dictionary.pageTitle) {
    document.title = dictionary.pageTitle;
}

if (dictionary.projectsPageTitle) {
    document.title = dictionary.projectsPageTitle;
}    


        if (!dictionary) {
            return;
        }


        translatableElements.forEach(element => {

            const key =
                element.dataset.i18n;


            if (dictionary[key] !== undefined) {

                applyTranslation(
                    element,
                    dictionary[key]
                );

            }

        });


        document.documentElement.lang =
            language;


        localStorage.setItem(
            "language",
            language
        );


        console.log(
            "Jazyk nastaven na:",
            language
        );
window.dispatchEvent(
    new CustomEvent("languageChanged", {
        detail: language
    })
);
    }


    languageButtons.forEach(button => {

        button.addEventListener(
            "click",
            () => {

                const language =
                    button.dataset.lang;

                setLanguage(language);

            }
        );

    });


    const savedLanguage =
        localStorage.getItem("language") || "cs";


    setLanguage(savedLanguage);

});